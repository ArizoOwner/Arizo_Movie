// Builds dist/worker.js: worker.js with wizard.html inlined, so the whole bot is
// ONE file that can be pasted into the Cloudflare dashboard or uploaded as-is.
//
// It also stamps the build identity the in-bot updater compares:
//   APP_VERSION  the package.json version (what people read)
//   BUILD_ID     first 12 hex chars of the SHA-256 of the finished file, computed
//                with the id itself set to zeros. Because it hashes the CONTENT,
//                re-uploading a changed file to an existing release is detected
//                as an update even though the version and tag did not change.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Line endings are normalised so the same sources give the same BUILD_ID on every
// platform (a Windows checkout with CRLF must not look like a different release).
const read = (name) => readFileSync(join(root, name), "utf8").replace(/\r\n/g, "\n");
const worker = read("worker.js");
const wizard = read("wizard.html");
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));

const importLine = 'import WIZARD_HTML from "./wizard.html";';
const versionLine = 'const APP_VERSION = "__SOURCE__";';
const buildLine = 'const BUILD_ID = "__SOURCE_BUILD__";';
for (const line of [importLine, versionLine, buildLine]) {
  if (!worker.includes(line)) throw new Error(`worker.js no longer contains: ${line}\nupdate scripts/build.mjs`);
}
if (!/^[0-9A-Za-z.+-]{1,32}$/.test(pkg.version)) throw new Error(`unsupported version string: ${pkg.version}`);

const ZERO_ID = "0".repeat(12);
const stamp = (id) =>
  `// Arizo_Movie v${pkg.version} - single-file Cloudflare Worker (generated by scripts/build.mjs)\n` +
  worker
    .replace(importLine, () => `const WIZARD_HTML = ${JSON.stringify(wizard)};`)
    .replace(versionLine, `const APP_VERSION = "${pkg.version}";`)
    .replace(buildLine, `const BUILD_ID = "${id}";`);

const id = createHash("sha256").update(stamp(ZERO_ID)).digest("hex").slice(0, 12);
const out = stamp(id);

mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "worker.js"), out);
console.log(`dist/worker.js written: v${pkg.version} build ${id} (${out.length} chars)`);
