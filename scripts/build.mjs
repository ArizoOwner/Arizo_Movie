// Builds dist/worker.js: worker.js with wizard.html inlined, so the whole bot is
// ONE file that can be pasted into the Cloudflare dashboard or uploaded as-is.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const worker = readFileSync(join(root, "worker.js"), "utf8");
const wizard = readFileSync(join(root, "wizard.html"), "utf8");

const importLine = 'import WIZARD_HTML from "./wizard.html";';
if (!worker.includes(importLine)) {
  throw new Error("worker.js no longer contains the wizard import; update scripts/build.mjs");
}

const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const header = `// Arizo_Movie v${pkg.version} - single-file Cloudflare Worker (generated by scripts/build.mjs)\n`;
const inlined = worker.replace(importLine, `const WIZARD_HTML = ${JSON.stringify(wizard)};`);

mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "worker.js"), header + inlined);
console.log(`dist/worker.js written (${(header.length + inlined.length / 1).toFixed(0)} chars)`);
